-- Bloque 31 · Plan de hábitos (pestaña Hábitos) y nombre libre de los entrenos
-- Pégalo entero en Supabase → SQL Editor → Run. Se puede ejecutar más de una vez sin romper nada.

-- 1. Nombre libre para cada día de entreno («Pierna y glúteo» en vez de «Martes»).
--    El día de la semana se sigue guardando en «nombre»: es el que decide cuándo le toca al alumno.
alter table public.dias add column if not exists titulo text;

-- 2. Hábitos del alumno: los del plan (propuestos, en instalación, en mantenimiento…) y los que añade el coach
create table if not exists public.habitos (
  id bigint generated by default as identity primary key,
  alumno_id uuid not null references public.perfiles(id) on delete cascade,
  clave text not null default 'propio',      -- del catálogo de la app (sueno_hora, pantallas, paseo…) o 'propio'
  titulo text not null,
  si_entonces text,                           -- «Cuando termine de cenar → dejo el móvil fuera del dormitorio»
  minimo text,                                -- versión mínima: cuenta como cumplido
  porque text,                                -- por qué encaja con el alumno
  orden smallint not null default 1,
  estado text not null default 'propuesto'
    check (estado in ('propuesto', 'instalacion', 'mantenimiento', 'consolidado', 'pausado', 'descartado')),
  inicio date,                                -- día en que empezó a practicarlo
  confianza smallint check (confianza between 0 and 10),
  srbai jsonb not null default '{}'::jsonb,   -- automaticidad (1 a 7) en las semanas 4 y 8: {"4": 5.3, "8": 6}
  creado_at timestamptz not null default now()
);
create index if not exists habitos_alumno_idx on public.habitos (alumno_id, orden);

-- 3. Registro: un toque al día por hábito (hecho, versión mínima o no) y, en mantenimiento, uno por semana
create table if not exists public.habitos_registro (
  habito_id bigint not null references public.habitos(id) on delete cascade,
  alumno_id uuid not null references public.perfiles(id) on delete cascade,
  fecha date not null,                        -- en mantenimiento, el lunes de la semana
  valor text not null check (valor in ('hecho', 'minimo', 'no', 'semana')),
  dias smallint check (dias between 0 and 7), -- en mantenimiento: cuántos días lo hizo esa semana
  motivo text,                                -- si no lo hizo: olvido, sin tiempo, evento social, enfermedad, no me apetecía
  creado_at timestamptz not null default now(),
  primary key (habito_id, fecha)
);
create index if not exists habitos_registro_alumno_idx on public.habitos_registro (alumno_id, fecha desc);

-- 4. Privacidad: cada alumno ve y gestiona solo lo suyo; el coach lo ve y lo gestiona todo
alter table public.habitos enable row level security;
alter table public.habitos_registro enable row level security;
grant select, insert, update, delete on public.habitos, public.habitos_registro to authenticated;

drop policy if exists habitos_alumno on public.habitos;
create policy habitos_alumno on public.habitos for all
  using (alumno_id = auth.uid())
  with check (alumno_id = auth.uid());

drop policy if exists habitos_coach on public.habitos;
create policy habitos_coach on public.habitos for all
  using (exists (select 1 from public.perfiles p where p.id = auth.uid() and p.rol = 'coach'))
  with check (exists (select 1 from public.perfiles p where p.id = auth.uid() and p.rol = 'coach'));

drop policy if exists habitos_registro_alumno on public.habitos_registro;
create policy habitos_registro_alumno on public.habitos_registro for all
  using (alumno_id = auth.uid())
  with check (alumno_id = auth.uid() and exists (select 1 from public.habitos h where h.id = habito_id and h.alumno_id = auth.uid()));

drop policy if exists habitos_registro_coach on public.habitos_registro;
create policy habitos_registro_coach on public.habitos_registro for all
  using (exists (select 1 from public.perfiles p where p.id = auth.uid() and p.rol = 'coach'))
  with check (exists (select 1 from public.perfiles p where p.id = auth.uid() and p.rol = 'coach'));
