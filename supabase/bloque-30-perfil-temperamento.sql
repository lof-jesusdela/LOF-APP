-- Bloque 30 · Perfil de temperamento (autodiagnóstico del alumno y seguimiento del piloto de 8 semanas)
-- Pégalo entero en Supabase → SQL Editor → Run. Se puede ejecutar más de una vez sin romper nada.

-- 1. El coach pide el cuestionario desde la ficha: el alumno lo ve en Hoy hasta que lo hace
alter table public.perfiles add column if not exists temperamento_pedido date;

-- 2. Un cuestionario por fila (el de partida y el de las 8 semanas)
create table if not exists public.temperamentos (
  id bigint generated by default as identity primary key,
  alumno_id uuid not null references public.perfiles(id) on delete cascade,
  fecha date not null default current_date,
  version smallint not null default 1,
  respuestas jsonb not null,                 -- 20 respuestas, hábitos, cronotipo y orden en que se vieron
  calor smallint not null check (calor between -10 and 10),
  humedad smallint not null check (humedad between -10 and 10),
  dominante text check (dominante in ('colerico', 'melancolico', 'sanguineo', 'flematico')),
  secundario text check (secundario in ('colerico', 'melancolico', 'sanguineo', 'flematico')),
  tendencia text check (tendencia in ('colerico', 'melancolico', 'sanguineo', 'flematico')),
  confianza text not null check (confianza in ('alta', 'media', 'baja')),
  cronotipo text check (cronotipo in ('matutino', 'intermedio', 'vespertino')),
  rmeq smallint check (rmeq between 4 and 25),
  senales text[] not null default '{}',      -- señales para derivar que marcó el alumno
  seguimiento jsonb not null default '{}'::jsonb,  -- revisiones de las semanas 2, 4, 6 y 8 y la decisión del coach
  creado_at timestamptz not null default now()
);
create index if not exists temperamentos_alumno_idx on public.temperamentos (alumno_id, fecha desc);

-- 3. Privacidad: cada alumno ve y guarda solo lo suyo; el coach lo ve y lo gestiona todo
alter table public.temperamentos enable row level security;
grant select, insert, update, delete on public.temperamentos to authenticated;

drop policy if exists temperamentos_alumno_ve on public.temperamentos;
create policy temperamentos_alumno_ve on public.temperamentos for select
  using (alumno_id = auth.uid());

drop policy if exists temperamentos_alumno_guarda on public.temperamentos;
create policy temperamentos_alumno_guarda on public.temperamentos for insert
  with check (alumno_id = auth.uid());

drop policy if exists temperamentos_coach on public.temperamentos;
create policy temperamentos_coach on public.temperamentos for all
  using (exists (select 1 from public.perfiles p where p.id = auth.uid() and p.rol = 'coach'))
  with check (exists (select 1 from public.perfiles p where p.id = auth.uid() and p.rol = 'coach'));
